/// Table index for a given data length (`len & 0x3FF`).
pub fn table_offset(len: usize) -> usize {
    len & 0x3FF
}

/// XORs the first (up to) 32 bytes of `payload` with the table starting at `offset`.
pub fn decrypt(payload: &[u8], offset: usize) -> Vec<u8> {
    let mut decoded = payload.to_vec();
    let crypted_length = decoded.len().min(32);
    for i in 0..crypted_length {
        let idx = offset + i;
        if idx >= DECRYPT_TABLE.len() {
            break;
        }
        decoded[i] ^= DECRYPT_TABLE[idx];
    }
    decoded
}

/// Decrypts a stored (uncompressed) block; returns the payload unchanged if no variant matches.
pub fn try_decrypt_aion_block(payload: &[u8], expected_size: usize, expected_crc32: u32) -> Vec<u8> {
    if payload.len() == expected_size && (expected_crc32 == 0 || crc32fast::hash(payload) == expected_crc32) {
        return payload.to_vec();
    }
    let decoded = decrypt(payload, table_offset(expected_size));
    if decoded.len() == expected_size && (expected_crc32 == 0 || crc32fast::hash(&decoded) == expected_crc32) {
        return decoded;
    }
    payload.to_vec()
}

pub fn inflate_raw(compressed: &[u8], out_size: usize) -> Result<Vec<u8>, std::io::Error> {
    if compressed.is_empty() {
        return Ok(Vec::new());
    }
    let options = DeflateOptions::default().set_size_hint(out_size);
    let mut decoder = DeflateDecoder::new_with_options(compressed, options);
    decoder.decode_deflate()
        .map_err(|_| std::io::Error::new(std::io::ErrorKind::InvalidData, "decompression failed"))
}

/// Attempts decompressing a slice with XOR header decryption.
fn inflate_with_header_xor(compressed: &[u8], out_size: usize, offset: usize) -> Result<Vec<u8>, std::io::Error> {
    let head_len = compressed.len().min(32);
    let table_end = offset.saturating_add(head_len).min(DECRYPT_TABLE.len());
    let xored_len = table_end.saturating_sub(offset);
    let mut data = Vec::with_capacity(compressed.len());
    for i in 0..xored_len {
        data.push(compressed[i] ^ DECRYPT_TABLE[offset + i]);
    }
    data.extend_from_slice(&compressed[xored_len..]);
    let options = DeflateOptions::default().set_size_hint(out_size);
    let mut decoder = DeflateDecoder::new_with_options(&data, options);
    decoder.decode_deflate()
        .map_err(|_| std::io::Error::new(std::io::ErrorKind::InvalidData, "decompression failed"))
}

/// Attempts extraction: first checks raw DEFLATE, then tries the decrypt table if encrypted.
pub fn decompress_and_decrypt(
    compressed: &[u8],
    uncompressed_size: usize,
    expected_crc32: u32,
) -> Result<Vec<u8>, std::io::Error> {
    // 1. Try the table using compressed length
    if let Ok(data) = inflate_with_header_xor(compressed, uncompressed_size, table_offset(compressed.len())) {
        if expected_crc32 == 0 || crc32fast::hash(&data) == expected_crc32 {
            return Ok(data);
        }
    }
    // 2. Try raw (no encryption)
    if let Ok(data) = inflate_raw(compressed, uncompressed_size) {
        if expected_crc32 == 0 || crc32fast::hash(&data) == expected_crc32 {
            return Ok(data);
        }
    }
    Err(std::io::Error::new(
        std::io::ErrorKind::InvalidData,
        "Failed to decompress Aion PAK block",
    ))
}
